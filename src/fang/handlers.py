"""Alert action handlers.

Handlers never execute commands and never touch the network. The only
"active" outputs are files: a JSON-lines alert log and an optional blocklist
that an administrator can feed to nftables/ipset on their own terms.
"""

from __future__ import annotations

import ipaddress
import json
import os
import stat
from abc import ABC, abstractmethod
from typing import Any, TextIO

from ._version import __version__
from .models import SecurityAlert, Severity
from .util import Allowlist, atomic_write_text, is_protected_ip, normalize_ip

_BLOCKLIST_MAX_ENTRIES = 1_000_000
_SUGGESTED_DURATION = {Severity.MEDIUM: 3600, Severity.HIGH: 14400, Severity.CRITICAL: 86400}


class ActionHandler(ABC):
    """Receives every alert that survives deduplication."""

    @abstractmethod
    def handle(self, alert: SecurityAlert) -> None: ...

    def close(self) -> None:  # noqa: B027 - optional hook
        """Flush and release resources."""


class JsonlAlertHandler(ActionHandler):
    """Append one compact JSON object per alert (SIEM / Filebeat friendly).

    The file is opened with ``O_NOFOLLOW`` and mode 0600, so a planted symlink
    cannot redirect a privileged write, and each alert is a single ``write``.
    """

    def __init__(self, path: str | os.PathLike[str]) -> None:
        # O_NONBLOCK: opening a FIFO for writing would otherwise block forever
        # waiting for a reader; with it the open fails fast (ENXIO) instead.
        flags = os.O_WRONLY | os.O_APPEND | os.O_CREAT | getattr(os, "O_NOFOLLOW", 0) | os.O_NONBLOCK
        fd = os.open(os.fspath(path), flags, 0o600)
        if not stat.S_ISREG(os.fstat(fd).st_mode):
            os.close(fd)
            raise OSError(f"{path}: not a regular file")
        self._fd: int | None = fd

    def handle(self, alert: SecurityAlert) -> None:
        if self._fd is None:
            raise ValueError("handler is closed")
        data = (json.dumps(alert.to_dict(), separators=(",", ":"), ensure_ascii=True) + "\n").encode()
        view = memoryview(data)
        while view:
            written = os.write(self._fd, view)
            view = view[written:]

    def close(self) -> None:
        if self._fd is not None:
            os.close(self._fd)
            self._fd = None


def _blockable(ip: str, allowlist: Allowlist) -> bool:
    return normalize_ip(ip) == ip and not is_protected_ip(ip) and ip not in allowlist


class BlocklistHandler(ActionHandler):
    """Maintain a plain text blocklist: one IP per line, comments with ``#``.

    Loopback, link-local, multicast, reserved and allow-listed addresses are
    never written. Existing valid entries are preserved, and every update is an
    atomic file replacement so a consumer never reads a half-written list.
    """

    def __init__(
        self,
        path: str | os.PathLike[str],
        allowlist: Allowlist | None = None,
        min_severity: Severity = Severity.HIGH,
    ) -> None:
        self.path = os.fspath(path)
        self.allowlist = allowlist if allowlist is not None else Allowlist()
        self.min_severity = min_severity
        self.entries: set[str] = set()
        self._load_existing()

    def _load_existing(self) -> None:
        try:
            fd = os.open(self.path, os.O_RDONLY | os.O_NONBLOCK)  # never block on a FIFO
        except FileNotFoundError:
            return
        if not stat.S_ISREG(os.fstat(fd).st_mode):
            os.close(fd)
            raise OSError(f"{self.path}: not a regular file")
        with os.fdopen(fd, encoding="utf-8", errors="replace") as handle:
            for count, line in enumerate(handle):
                if count >= _BLOCKLIST_MAX_ENTRIES:
                    break
                text = line.split("#", 1)[0].strip()
                ip = normalize_ip(text) if text else None
                if ip is not None and _blockable(ip, self.allowlist):
                    self.entries.add(ip)

    def handle(self, alert: SecurityAlert) -> None:
        if alert.severity.rank < self.min_severity.rank:
            return
        added = False
        for ip in alert.block_candidates:
            if _blockable(ip, self.allowlist) and ip not in self.entries:
                if len(self.entries) >= _BLOCKLIST_MAX_ENTRIES:
                    break
                self.entries.add(ip)
                added = True
        if added:
            self._write()

    def _write(self) -> None:
        header = (
            f"# Generated by Fang {__version__}. One IP per line. Review before enforcing.\n"
            f"# Never contains loopback, link-local, multicast, reserved or allow-listed addresses.\n"
        )
        ordered = sorted(
            self.entries,
            key=lambda ip: (ipaddress.ip_address(ip).version, int(ipaddress.ip_address(ip))),
        )
        atomic_write_text(self.path, header + "".join(f"{ip}\n" for ip in ordered), mode=0o600)

    def close(self) -> None:
        return None


class NetAccessControllerHook(ActionHandler):
    """Dry-run integration point for ``net-access-controller``.

    Builds the canonical block payload for every blockable address of an alert
    and prints it. Nothing is ever executed or sent.
    """

    def __init__(self, allowlist: Allowlist | None = None, stream: TextIO | None = None) -> None:
        self.allowlist = allowlist if allowlist is not None else Allowlist()
        self.stream = stream
        self.payloads: list[dict[str, Any]] = []

    @staticmethod
    def build_block_payload(alert: SecurityAlert, ip: str | None = None) -> dict[str, Any]:
        target = (
            ip if ip is not None else (alert.source_ip or (alert.source_ips[0] if alert.source_ips else ""))
        )
        return {
            "schema_version": "1.0",
            "action": "BLOCK_IP",
            "target_ip": target,
            "reason": alert.pattern,
            "severity": alert.severity.value,
            "suggested_duration_seconds": _SUGGESTED_DURATION[alert.severity],
            "evidence": {
                "alert_id": alert.alert_id,
                "failed_attempts": alert.attempts,
                "time_window_seconds": alert.window_seconds,
                "targeted_usernames": alert.target_usernames,
            },
            "triggered_by": "fang",
        }

    def handle(self, alert: SecurityAlert) -> None:
        for ip in alert.block_candidates:
            if not _blockable(ip, self.allowlist):
                continue
            payload = self.build_block_payload(alert, ip)
            self.payloads.append(payload)
            if self.stream is not None:
                self.stream.write(
                    "[dry-run] net-access-controller payload: "
                    + json.dumps(payload, separators=(",", ":"), ensure_ascii=True)
                    + "\n"
                )
                self.stream.flush()
